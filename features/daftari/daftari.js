"use client";

import { useState } from "react";
import { Brain as BrainIcon, FilePlus2, ScanLine } from "lucide-react";
import { SegmentedControl } from "@/components/ui/segmented-control";
import { useToast } from "@/components/ui/toast";
import { FACTS, ITEMS, SCANNED_ITEM } from "./data/brain";
import { DEFAULT_INSTRUCTIONS } from "./lib/generate";
import { Brain } from "./components/brain";
import { Capture } from "./components/capture";
import { Create } from "./components/create";

const TABS = [
  { value: "capture", label: "Capture", icon: <ScanLine className="size-4" aria-hidden="true" /> },
  { value: "brain", label: "Brain", icon: <BrainIcon className="size-4" aria-hidden="true" /> },
  { value: "create", label: "Create", icon: <FilePlus2 className="size-4" aria-hidden="true" /> },
];

const initialCreate = {
  step: 1,
  phase: "wizard", // wizard → generating → result
  instructions: DEFAULT_INSTRUCTIONS,
  src: { format: "fmt-midterm", bank: "bank-b2", data: "none", golden: true, official: true },
  exam: null,
  version: "A",
  edits: {},
  tab: "exam",
  editing: false,
  showSources: true,
  savedGolden: false,
};

/**
 * The Daftari prototype. Everything lives here so switching between Capture, Brain and Create keeps your work, and
 * "Reset demo" (which remounts this component) returns to the start. Opens on Capture with the Brain already filled.
 */
export function Daftari() {
  const toast = useToast();
  const [tab, setTab] = useState("capture");
  const [items, setItems] = useState(ITEMS);
  const [facts, setFacts] = useState(FACTS);
  const [folder, setFolder] = useState("formats");
  const [cap, setCap] = useState({ phase: "idle", resolved: {}, saved: false });
  const [cr, setCr] = useState(initialCreate);

  const saveScan = () => {
    setItems((all) => (all.some((i) => i.id === SCANNED_ITEM.id) ? all : [...all, SCANNED_ITEM]));
    setCap((c) => ({ ...c, saved: true }));
    toast("Saved to Brain › Formats");
  };

  const saveGolden = (name) => {
    setItems((all) => [
      ...all,
      { id: "gold-generated", folder: "golden", name, kind: "text", source: "typed", updated: "Just now", usedIn: 0, on: true, summary: "An exam and marking scheme generated by Daftari from your format and question bank." },
    ]);
    setCr((c) => ({ ...c, savedGolden: true }));
    toast("Saved to Brain › Golden examples");
  };

  return (
    <div className="p-base md:p-group">
      <div className="mb-base">
        <SegmentedControl label="Daftari" options={TABS} value={tab} onChange={setTab} />
      </div>
      {tab === "capture" ? (
        <Capture
          cap={cap}
          setCap={setCap}
          onSave={saveScan}
          onOpenBrain={() => {
            setFolder("formats");
            setTab("brain");
          }}
        />
      ) : null}
      {tab === "brain" ? <Brain items={items} setItems={setItems} facts={facts} setFacts={setFacts} folder={folder} setFolder={setFolder} /> : null}
      {tab === "create" ? <Create cr={cr} setCr={setCr} items={items} facts={facts} onSaveGolden={saveGolden} /> : null}
    </div>
  );
}
